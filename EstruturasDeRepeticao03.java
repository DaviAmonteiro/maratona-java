public class EstruturasDeRepeticao03 {
    static void main() {
        // Imprima os primeiros 25 valores de uma lista com 50 números.
        int valorMax = 50;
        for (int i = 0; i <=valorMax; i++) {
            if (i>25)
                break;
            System.out.println(i);
        }
    }
}
